# Create a string
s = "hello python programming"

print("Original String:", s)

# 1. upper()
print("Uppercase:", s.upper())

# 2. lower()
print("Lowercase:", s.lower())

# 3. capitalize()
print("Capitalize:", s.capitalize())

# 4. title()
print("Title:", s.title())

# 5. count()
print("Count of o:", s.count('o'))

# 6. find()
print("Position of python:", s.find("python"))

# 7. replace()
print("After replace:", s.replace("python", "java"))

# 8. startswith()
print("Starts with hello:", s.startswith("hello"))

# 9. endswith()
print("Ends with programming:", s.endswith("programming"))

# 10. split()
print("After split:", s.split())