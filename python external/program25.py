import numpy as np

# Create an array
a = np.array([10, 20, 30, 40, 50])

print("Array:", a)

# Display array elements
print("First Element:", a[0])

# Addition
print("Addition:", a + 10)

# Multiplication
print("Multiplication:", a * 2)

# Find sum
print("Sum:", np.sum(a))

# Find maximum
print("Maximum:", np.max(a))

# Find minimum
print("Minimum:", np.min(a))

# Find mean
print("Mean:", np.mean(a))

# Find array size
print("Size:", a.size)

# Find array dimension
print("Dimension:", a.ndim)